  function announce(events) {
    if (!state || state.phase !== 'playing') return; // the results dialog tells the rest
    const you = state.you;
    for (const e of events) {
      const mine = e.playerId === you;
      const n = nameOf(e.playerId);
      switch (e.type) {
        case 'play':
          if (e.cards && e.cards.length > 1) {
            const same = e.cards.every(c => c.value === e.card.value);
            const what = same ? `${e.cards.length} × ${isNum(e.card.value) ? e.card.value : VALUE_NAME[e.card.value]}` : e.cards.map(cardLabel).join(' + ');
            toast(`${n} dropped ${what} at once!`, 'last');
          }
          break;
        case 'skip':
          toast(mine ? 'You’re skipped!' : `${n} is skipped`, mine ? 'bad' : '');
          break;
        case 'reverse':
          toast('Direction reversed');
          break;
        case 'draw':
          if (e.forced && e.count) toast(mine ? `You draw ${e.count}` : `${n} draws ${e.count}`, mine ? 'bad' : '');
          break;
        case 'stack':
          if (mine) toast(`+${e.amount} headed your way — stack, bounce or take it`, 'bad');
          break;
        case 'bounce':
          if (mine) toast(`${nameOf(e.by)} bounced it back — +${e.amount} for you!`, 'bad');
          else if (e.by === you) toast(`Bounced! +${e.amount} goes back to ${n}`, 'last');
          else toast(`${nameOf(e.by)} bounced +${e.amount} back to ${n}`);
          break;
        case 'last':
          toast(`${n}: “Last card!”`, 'last');
          break;
        case 'caught':
          if (mine) toast(`${nameOf(e.by)} caught you! Draw ${e.count}`, 'caught');
          else if (e.by === you) toast(`Gotcha! ${n} draws ${e.count}`, 'caught');
          else toast(`${nameOf(e.by)} caught ${n}`, 'caught');
          break;
        default:
          break;
      }
    }
  }

