  function runFlights(flights, events) {
    let t = 0;
    const pileRect = $('#discard').getBoundingClientRect();
    flights.forEach((f, k) => {
      fly({ face: cardHTML(f.card), from: f.from, to: pileRect, delay: k * 80, flip: f.flip });
      t = 260 + k * 80;
    });
    const deck = $('#deckCard');
    if (!deck) return;
    const deckRect = deck.getBoundingClientRect();
    let handled = false;
    for (const e of events) {
      if ((e.type !== 'draw' && e.type !== 'caught') || !e.count) continue;
      if (e.playerId === state.you) {
        if (handled) continue;
        handled = true;
        // Your new cards turn face up as they land in your hand.
        $$('#hand .card.new').forEach((el, k) => {
          const delay = t + k * 90;
          const rect = restingRect(el);
          el.style.animationDelay = `${delay + 320}ms`;
          const card = state.game.hand.find(c => c.id === Number(el.dataset.id));
          fly({ face: card ? cardHTML(card) : backHTML(), from: deckRect, to: rect, delay, flip: !!card });
        });
        t += 200;
      } else {
        const seat = $(`[data-seat="${CSS.escape(e.playerId)}"] .seat-hand`);
        if (!seat) continue;
        const to = smallRect(seat.getBoundingClientRect());
        const count = Math.min(e.count, 6);
        for (let k = 0; k < count; k++) fly({ face: backHTML(), from: deckRect, to, delay: t + k * 90, fade: true });
        t += count * 90 + 100;
      }
    }
  }

  function fly({ face, from, to, delay = 0, fade = false, flip = false }) {
    if (!to.width) return;
    const el = document.createElement('div');
    el.className = 'flyer';
    const w = to.width;
    const h = w * 1.4;
    el.style.setProperty('--cw', `${w}px`);
    el.innerHTML = flip ? `<div class="flip">${face}${backHTML('flip-back')}</div>` : face;
    const x = to.left + to.width / 2 - w / 2;
    const y = to.top + to.height / 2 - h / 2;
    el.style.left = `${x}px`;
    el.style.top = `${y}px`;
    document.body.append(el);
    const dx = from.left + from.width / 2 - (x + w / 2);
    const dy = from.top + from.height / 2 - (y + h / 2);
    const timing = { duration: 360, delay, easing: 'cubic-bezier(.2,.75,.25,1)', fill: 'backwards' };
    const anim = el.animate(
      [
        { transform: `translate(${dx}px, ${dy}px) scale(${from.width / w}) rotate(-8deg)`, opacity: 1 },
        { transform: `translate(${dx * 0.4}px, ${dy * 0.4 - 30}px) scale(${(from.width / w + 1) / 2 + 0.08}) rotate(-3deg)`, opacity: 1, offset: 0.55 },
        { transform: 'translate(0, 0) scale(1) rotate(0deg)', opacity: fade ? 0.15 : 1 },
      ],
      timing
    );
    if (flip) el.firstElementChild.animate([{ transform: 'rotateY(180deg)' }, { transform: 'rotateY(0deg)' }], timing);
    anim.onfinish = () => el.remove();
    anim.oncancel = () => el.remove();
  }

