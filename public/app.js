  /** Measure where played cards come from before the DOM is replaced. */
  function captureFlights(events) {
    const out = [];
    for (const e of events) {
      if (e.type !== 'play') continue;
      const mine = e.playerId === state.you;
      const seat = $(`[data-seat="${CSS.escape(e.playerId)}"] .seat-hand`);
      const seatRect = seat ? smallRect(seat.getBoundingClientRect()) : null;
      for (const card of e.cards || [e.card]) {
        let from = null;
        if (mine) {
          const el = $(`#hand [data-id="${card.id}"]`);
          if (el) from = el.getBoundingClientRect();
        }
        if (!from) from = seatRect;
        // Opponents' cards are face down until they hit the pile, so they flip on the way.
        if (from && from.width) out.push({ kind: 'play', from, card, flip: !mine });
      }
    }
    return out;
  }

