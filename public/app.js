  function onCardClick(btn) {
    const g = state && state.game;
    if (!g || !btn || !g.hand) return;
    const id = Number(btn.dataset.id);
    const card = g.hand.find(c => c.id === id);
    if (!card) return;
    const myTurn = g.turn === state.you;

    // Building a multi-drop: tap to add or remove cards that combine with the selection.
    if (selection && myTurn) {
      if (selection.ids.has(id)) {
        selection.ids.delete(id);
        if (!selectionValid()) selection = null;
        renderTable(null);
        return;
      }
      if (canCombine([...selectedCards(), card]) && (!g.pendingDraw || card.value === 'draw2')) {
        selection.ids.add(id);
        renderTable(null);
        return;
      }
      selection = null; // tapped a different card: start over with it
      renderTable(null);
    }

    if (!g.playable.includes(id)) {
      const el = $(`#hand [data-id="${id}"]`);
      if (el) {
        el.classList.remove('shake');
        void el.offsetWidth;
        el.classList.add('shake');
      }
      if (myTurn) {
        if (g.pendingDraw && g.pendingKind === 'wild4') toast(`Answer a +4 with a +4 or ${/^[AEIOU]/.test(COLOR_NAME[g.color]) ? 'an' : 'a'} ${COLOR_NAME[g.color]} Reverse — or take ${g.pendingDraw}`);
        else if (g.pendingDraw) toast(`Answer with +2s, ${/^[AEIOU]/.test(COLOR_NAME[g.color]) ? 'an' : 'a'} ${COLOR_NAME[g.color]} Reverse, or take ${g.pendingDraw}`);
        else if (g.drawnCardId !== null) toast('Only the card you just drew can be played');
        else toast('That card doesn’t match');
      }
      return;
    }
    if (card.color === 'wild') {
      openPicker([id], COLORS);
      return;
    }
    // Holding cards that can go down with it? Select them all; the player can then trim the set.
    const group = comboFor(card, g.hand);
    if (group.length > 1) {
      selection = { ids: new Set(group.map(c => c.id)), anchor: id };
      renderTable(null);
      return;
    }
    send({ t: 'play', cardIds: [id] });
  }

  function dropSelection() {
    if (!selectionValid()) {
      clearSelection();
      return;
    }
    const g = state.game;
    const ids = [...selection.ids];
    const colors = [...new Set(ids.map(id => g.hand.find(c => c.id === id).color))];
    if (colors.length > 1) {
      openPicker(ids, COLORS.filter(c => colors.includes(c)));
      return;
    }
    send({ t: 'play', cardIds: ids, color: colors[0] });
    selection = null;
  }

