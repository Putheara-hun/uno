  function enter(kind) {
    if (OPENED_AS_FILE) {
      homeMessage(FILE_HELP);
      return;
    }
    const name = $('#nameInput').value.trim();
    if (!name) {
      homeMessage('Pick a name first.');
      $('#nameInput').focus();
      return;
    }
    storageSet('localStorage', 'chroma.name', name);
    const code = $('#codeInput').value.trim().toUpperCase();
    if (kind === 'join' && !/^[A-Z]{4}$/.test(code)) {
      homeMessage('Room codes are 4 letters.');
      $('#codeInput').focus();
      return;
    }
    const msg = kind === 'create' ? { t: 'create', name } : { t: 'join', name, code };
    homeMessage(kind === 'create' ? 'Setting up your table…' : `Joining ${code}…`, true);
    setBusy(true);
    expectAnswer();
    if (ws && ws.readyState === WebSocket.OPEN && serverReady) ws.send(JSON.stringify(msg));
    else {
      queued = msg;
      if (!ws || ws.readyState === WebSocket.CLOSED) connect();
    }
  }

