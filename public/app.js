  /** Fan geometry: spacing (overlap when crowded), and per-card angle and arc drop. */
  function handGeometry(n) {
    const el = $('#hand');
    const cw = parseFloat(getComputedStyle(el).getPropertyValue('--cw')) || 86;
    const avail = el.clientWidth - 40 - cw * 0.4; // leave room for the outer cards' tilt
    const gap = 6;
    let step = gap;
    if (n > 1 && n * cw + (n - 1) * gap > avail) step = Math.max(-cw * 0.7, (avail - n * cw) / (n - 1));
    const spread = Math.min(34, n * 3.2);
    const pos = i => {
      const t = n > 1 ? i / (n - 1) - 0.5 : 0;
      return { fan: (t * spread).toFixed(2), drop: (t * t * cw * 0.3 * Math.min(1, n / 7)).toFixed(1) };
    };
    return { step, pos };
  }

